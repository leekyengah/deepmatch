import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const out = execSync("npx --yes supabase@2.120.0 status -o env", {
  encoding: "utf8",
  cwd: resolve(process.cwd()),
});

const map = Object.fromEntries(
  out
    .split(/\r?\n/)
    .filter((l) => l.includes("="))
    .map((l) => {
      const i = l.indexOf("=");
      return [l.slice(0, i), l.slice(i + 1).replace(/^"|"$/g, "")];
    }),
);

const env = `# Auto-generated by scripts/write-local-env.mjs — do not commit
NEXT_PUBLIC_APP_ENV=local
NEXT_PUBLIC_APP_URL=http://localhost:3000
NEXT_PUBLIC_ADMIN_URL=http://localhost:3001
NEXT_PUBLIC_SUPABASE_URL=${map.API_URL ?? map.SUPABASE_URL ?? ""}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${map.ANON_KEY ?? map.SUPABASE_ANON_KEY ?? ""}
SUPABASE_SERVICE_ROLE_KEY=${map.SERVICE_ROLE_KEY ?? map.SUPABASE_SERVICE_ROLE_KEY ?? ""}
FF_MATCHING=true
FF_CHAT=true
FF_MEDIA_UPLOAD=true
FF_CONCIERGE=false
FF_DISCOVERY=true
MIN_AGE=18
`;

writeFileSync(resolve(process.cwd(), "apps/web/.env.local"), env);
writeFileSync(resolve(process.cwd(), "apps/admin/.env.local"), env);
writeFileSync(resolve(process.cwd(), ".env.local"), env);
console.log("Wrote .env.local for root, web, admin");
