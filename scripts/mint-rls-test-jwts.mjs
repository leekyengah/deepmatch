/**
 * Mint staging JWTs for RLS deny matrix (FAR-11).
 * Writes ONLY to gitignored `.ai/rls-test.env.ps1` — never commits tokens.
 *
 * Prerequisites (trusted machine):
 *   - .env.local with NEXT_PUBLIC_SUPABASE_URL + ANON_KEY
 *   - .ai/qa.env.ps1 with QA_EMAIL_A, QA_EMAIL_B, QA_PASSWORD
 *   - Optional: RLS_TEST_PRIVATE_NOTE_ID_A (else creates a note as A)
 *
 * Usage:
 *   node --env-file=.env.local scripts/mint-rls-test-jwts.mjs
 *   . .\.ai\rls-test.env.ps1
 *   npm run qa:deepmatch -- --suite security --env dm-staging
 */
import { createClient } from "@supabase/supabase-js";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

function loadQaEnv() {
  try {
    const raw = readFileSync(".ai/qa.env.ps1", "utf8");
    for (const line of raw.split(/\r?\n/)) {
      const m = line.match(/^\$env:([A-Z0-9_]+)="(.*)"$/);
      if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
    }
  } catch {
    /* optional */
  }
}
loadQaEnv();

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const anon =
  process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY ||
  process.env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY;
const emailA = process.env.QA_EMAIL_A;
const emailB = process.env.QA_EMAIL_B;
const password = process.env.QA_PASSWORD;

if (!url || !anon || !emailA || !emailB || !password) {
  console.error(
    "Missing NEXT_PUBLIC_SUPABASE_* or QA_EMAIL_A/B + QA_PASSWORD (qa.env.ps1)",
  );
  process.exit(1);
}

async function signIn(email) {
  const client = createClient(url, anon, {
    auth: { autoRefreshToken: false, persistSession: false },
  });
  const { data, error } = await client.auth.signInWithPassword({
    email,
    password,
  });
  if (error) throw new Error(`${email}: ${error.message}`);
  return {
    token: data.session.access_token,
    userId: data.user.id,
    client,
    expiresAt: data.session.expires_at,
  };
}

const a = await signIn(emailA);
const b = await signIn(emailB);

let noteId = process.env.RLS_TEST_PRIVATE_NOTE_ID_A;
if (!noteId) {
  const { data: existing } = await a.client
    .from("private_notes")
    .select("id")
    .eq("author_id", a.userId)
    .eq("shared_with_partner", false)
    .limit(1)
    .maybeSingle();
  if (existing?.id) {
    noteId = existing.id;
  } else {
    const { data: pin } = await a.client
      .from("pins")
      .select("id")
      .limit(1)
      .maybeSingle();
    if (!pin?.id) {
      console.warn(
        "No pin for A — set RLS_TEST_PRIVATE_NOTE_ID_A manually (or run seed:qa).",
      );
    } else {
      const { data, error } = await a.client
        .from("private_notes")
        .insert({
          pin_id: pin.id,
          author_id: a.userId,
          body: `rls-harness-${Date.now()}`,
          shared_with_partner: false,
        })
        .select("id")
        .single();
      if (error) {
        console.warn(
          "Could not create private_notes — set RLS_TEST_PRIVATE_NOTE_ID_A:",
          error.message,
        );
      } else {
        noteId = data.id;
      }
    }
  }
}

mkdirSync(".ai", { recursive: true });
const outPath = join(".ai", "rls-test.env.ps1");
const lines = [
  "# AUTO-GENERATED — DO NOT COMMIT. Regenerated by scripts/mint-rls-test-jwts.mjs",
  `# minted_at=${new Date().toISOString()}`,
  `# expires_hint_A=${a.expiresAt ?? "unknown"} expires_hint_B=${b.expiresAt ?? "unknown"}`,
  `$env:SUPABASE_URL="${url}"`,
  `$env:SUPABASE_ANON_KEY="${anon}"`,
  `$env:NEXT_PUBLIC_SUPABASE_URL="${url}"`,
  `$env:NEXT_PUBLIC_SUPABASE_ANON_KEY="${anon}"`,
  `$env:RLS_TEST_USER_A_JWT="${a.token}"`,
  `$env:RLS_TEST_USER_B_JWT="${b.token}"`,
];
if (noteId) {
  lines.push(`$env:RLS_TEST_PRIVATE_NOTE_ID_A="${noteId}"`);
}
writeFileSync(outPath, lines.join("\n") + "\n", "utf8");

console.log(
  JSON.stringify(
    {
      ok: true,
      outPath,
      userA: a.userId,
      userB: b.userId,
      noteId: noteId ?? null,
      gitignored: true,
      next: [
        ". .\\.ai\\rls-test.env.ps1",
        "npm run qa:deepmatch -- --suite security --env dm-staging",
      ],
    },
    null,
    2,
  ),
);
